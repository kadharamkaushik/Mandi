#!/usr/bin/env python3
"""Rebuild tasks/INDEX.md from task front matter and check the dependency graph.

Usage:  python3 tasks/index.py          # rewrite INDEX.md
        python3 tasks/index.py --check  # validate only (CI); non-zero exit on problems
"""
import re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent
EPICS = {"PLAT": "Platform and infrastructure", "API": "Backend foundation", "STORE": "Store connectors and data",
         "CORE": "Product features (backend)", "IOS": "iOS app", "AND": "Android app", "QA": "Quality, launch and compliance"}
STATUSES = ["todo", "in-progress", "in-review", "done", "blocked"]


def front_matter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    meta = {}
    for line in (m.group(1).splitlines() if m else []):
        k, _, v = line.partition(":")
        v = v.strip()
        if len(v) >= 2 and v[0] == v[-1] == '"':
            v = v[1:-1]
        if v.startswith("[") and v.endswith("]"):
            v = [x.strip() for x in v[1:-1].split(",") if x.strip()]
        meta[k.strip()] = v
    return meta


def load():
    tasks = {}
    for p in sorted(ROOT.glob("*/MND-*.md")):
        meta = front_matter(p.read_text(encoding="utf-8"))
        meta["path"] = p.relative_to(ROOT).as_posix()
        tasks[meta["id"]] = meta
    return tasks


def waves(tasks):
    level, problems = {}, []
    def visit(tid, stack):
        if tid in level:
            return level[tid]
        if tid in stack:
            problems.append("cycle: " + " -> ".join(stack + [tid]))
            return 0
        deps = tasks[tid].get("depends_on") or []
        lv = 1
        for d in deps:
            if d not in tasks:
                problems.append(f"{tid} depends on unknown {d}")
                continue
            lv = max(lv, visit(d, stack + [tid]) + 1)
        level[tid] = lv
        return lv
    for tid in tasks:
        visit(tid, [])
    for tid, t in tasks.items():
        if t.get("status") not in STATUSES:
            problems.append(f"{tid} has invalid status {t.get('status')!r}")
    return level, problems


def ready(tasks):
    return [tid for tid, t in tasks.items() if t.get("status") == "todo"
            and all(tasks.get(d, {}).get("status") == "done" for d in (t.get("depends_on") or []))]


def render(tasks, level):
    counts = {s: sum(1 for t in tasks.values() if t.get("status") == s) for s in STATUSES}
    out = ["# Implementation backlog", "",
           "Generated by `python3 tasks/index.py` from each task's front matter. Do not edit this table by hand; change the task file and rerun.", "",
           "Status: " + " · ".join(f"{k} {v}" for k, v in counts.items()) + f" · total {len(tasks)}", "",
           "**Wave** = earliest round a task can start if every dependency is done; tasks in the same wave can run in parallel Cowork sessions.", "",
           "## Ready to pick up now", ""]
    r = sorted(ready(tasks), key=lambda x: (level[x], x))
    out += [f"- [{x}]({tasks[x]['path']}) — {tasks[x]['title']} ({tasks[x].get('owner')})" for x in r] or ["- none"]
    out += ["", "## All tasks", "", "| Wave | ID | Title | Epic | PRD | Owner | Size | Depends on | Status |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for tid in sorted(tasks, key=lambda x: (level[x], x)):
        t = tasks[tid]
        deps = ", ".join(t.get("depends_on") or []) or "—"
        out.append(f"| {level[tid]} | [{tid}]({t['path']}) | {t['title']} | {t['epic']} | {t.get('prd','')} | {t.get('owner','')} | {t.get('size','')} | {deps} | {t.get('status')} |")
    out += ["", "## Epics", ""] + [f"- **{k}** — {v}" for k, v in EPICS.items()]
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    tasks = load()
    level, problems = waves(tasks)
    if problems:
        print("\n".join(problems)); sys.exit(1)
    if "--check" in sys.argv:
        print(f"ok: {len(tasks)} tasks, max wave {max(level.values())}"); sys.exit(0)
    (ROOT / "INDEX.md").write_text(render(tasks, level), encoding="utf-8")
    print(f"wrote INDEX.md: {len(tasks)} tasks, max wave {max(level.values())}")
